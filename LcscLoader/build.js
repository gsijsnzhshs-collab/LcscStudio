#!/usr/bin/env node
// Builds LcscLoader.dll against a resolved Altium Designer SDK.
// Usage: node build.js [--sdk-dir <dir>] [--ad-version <20|24|25>]
// Resolution order: --sdk-dir > AD_SDK_DIR > auto-detection. See tools/ad-sdk.js.

const { spawnSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const adSdk = require(path.join(__dirname, '..', 'tools', 'ad-sdk'));
const versionInfo = require(path.join(__dirname, '..', 'tools', 'version'));

const root = path.resolve(__dirname, '..');
const csc = path.join(root, '_tools', 'roslyn', 'tasks', 'net472', 'csc.exe');
const refsTemplate = path.join(root, '_tools', 'refs.rsp');
const net48RefDir = path.join(root, '_tools', 'net48ref');
const refsGenerated = path.join(root, '_tools', 'refs.generated.rsp');
const outDir = path.join(__dirname, 'bin');

let cli;
let sdk;
try {
  cli = adSdk.parseArgs(process.argv.slice(2));
  sdk = adSdk.resolveSdkDir(cli);
} catch (error) {
  console.error('ERROR: ' + error.message);
  process.exit(1);
}
const sdkDir = sdk.dir;
console.log('SDK: ' + sdkDir + '  [' + sdk.source + (sdk.version ? ', AD' + sdk.version : '') + ']');
const dll = path.join(outDir, 'LcscLoader.dll');
const sourceDir = path.join(__dirname, 'src');
const uiDir = path.join(root, 'LcscStudio', 'src');

// version.json is the only place the version is written: it drives the generated
// AssemblyVersion, the rendered .Ins and the registry value written by deploy.js.
let version;
try {
  version = versionInfo.read();
} catch (error) {
  console.error('ERROR: ' + error.message);
  process.exit(1);
}
console.log('version: ' + version);

const generatedVersionFile = path.join(sourceDir, 'BuildVersion.cs');
fs.writeFileSync(generatedVersionFile, [
  '// <auto-generated> generated by build.js from version.json; do not edit or commit.',
  'using System.Reflection;',
  '',
  '[assembly: AssemblyVersion("' + version + '")]',
  '[assembly: AssemblyFileVersion("' + version + '")]',
  '',
].join('\r\n'), 'utf8');

// Explicit exclusions only; everything else is discovered by scanning, so new files
// are picked up automatically. Paths are relative to the repository root.
const EXCLUDED_SOURCES = {
  'LcscLoader/src/MainForm.cs': 'dead code (removed in T4-6)',
  'LcscStudio/src/PanelControl.cs': 'WPF UI (dropped by D3)',
  'LcscStudio/src/Preview2D.cs': 'WPF UI (dropped by D3)',
  'LcscStudio/src/Preview3D.cs': 'WPF UI (dropped by D3)',
  'LcscStudio/src/PreviewFootprint.cs': 'WPF UI (dropped by D3)',
  'LcscStudio/src/SettingsWindow.cs': 'WPF UI (dropped by D3)',
  'LcscStudio/src/TargetWindow.cs': 'WPF UI (dropped by D3)',
  'LcscStudio/src/UiTheme.cs': 'WPF UI (dropped by D3)',
};

function relativeToRoot(file) {
  return path.relative(root, file).split(path.sep).join('/');
}

function walkCs(dir) {
  const result = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) result.push(...walkCs(full));
    else if (entry.isFile() && entry.name.endsWith('.cs')) result.push(full);
  }
  return result;
}

const sources = [...walkCs(sourceDir), ...walkCs(uiDir)]
  .filter(file => !(relativeToRoot(file) in EXCLUDED_SOURCES))
  .sort((a, b) => relativeToRoot(a).localeCompare(relativeToRoot(b), 'en'));

console.log('sources: ' + sources.length + ' files');
for (const file of sources) console.log('  ' + relativeToRoot(file));

if (cli.rest.includes('--list-sources')) {
  process.exit(0);
}

// refs.rsp keeps repo-relative paths so the repository stays portable; csc gets
// an expanded response file with absolute paths generated next to it.
function expandRefs() {
  if (!fs.existsSync(csc)) {
    throw new Error('Missing compiler: ' + csc + '\n  run: node tools/restore-tools.js');
  }
  if (!fs.existsSync(refsTemplate)) {
    throw new Error('Missing reference list: ' + refsTemplate);
  }

  const lines = fs.readFileSync(refsTemplate, 'utf8')
    .split(/\r?\n/)
    .map(line => line.trim())
    .filter(Boolean);

  const missing = [];
  const expanded = lines.map(line => {
    const match = line.match(/^\/r:(?:"([^"]+)"|(.+))$/);
    if (!match) throw new Error('Unrecognized line in refs.rsp: ' + line);
    const target = match[1] || match[2];
    const isAbsolute = /^[A-Za-z]:/.test(target) || target.startsWith('/');
    if (isAbsolute) {
      if (!fs.existsSync(target)) missing.push(target);
      return line;
    }
    const full = path.join(net48RefDir, target.split(/[\\/]/).join(path.sep));
    if (!fs.existsSync(full)) missing.push(full);
    return '/r:"' + full + '"';
  });

  if (missing.length) {
    throw new Error('Missing ' + missing.length + ' of ' + lines.length +
      ' reference assemblies, e.g.:\n  ' + missing[0] +
      '\n  run: node tools/restore-tools.js');
  }

  fs.writeFileSync(refsGenerated, expanded.join('\r\n') + '\r\n', 'utf8');
  return { file: refsGenerated, count: lines.length };
}

let refs;
try {
  refs = expandRefs();
  console.log('references: ' + refs.count + ' assemblies from ' + path.relative(root, net48RefDir));
} catch (error) {
  console.error('ERROR: ' + error.message);
  process.exit(1);
}

fs.mkdirSync(outDir, { recursive: true });

// The .Ins is rendered from a template so its Version/Date cannot drift from version.json.
const insTemplate = path.join(__dirname, 'LCSCLoader.Ins.tmpl');
const insOutput = path.join(outDir, 'LCSCLoader.Ins');
if (!fs.existsSync(insTemplate)) {
  console.error('ERROR: missing template ' + insTemplate);
  process.exit(1);
}
fs.writeFileSync(insOutput,
  fs.readFileSync(insTemplate, 'utf8')
    .replace(/@VERSION@/g, version)
    .replace(/@DATE@/g, versionInfo.insDate(new Date())),
  'utf8');

const args = [
  '-nologo',
  '-target:library',
  '-out:' + dll,
  '-langversion:7.3',
  '-deterministic',
  '/pathmap:' + root + '=/_/',
  '@' + refs.file,
  '/r:' + path.join(sdkDir, 'Altium.SDK.dll'),
  '/r:' + path.join(sdkDir, 'Altium.SDK.Interfaces.dll'),
  '/r:' + path.join(sdkDir, 'Newtonsoft.Json.dll'),
  ...sources,
];

const result = spawnSync(csc, args, { stdio: 'inherit' });
if (result.error) {
  console.error('ERROR: ' + result.error.message);
  process.exit(1);
}
if (result.status !== 0) {
  process.exit(result.status);
}

function sha256File(file) {
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex').toUpperCase();
}

function gitSnapshot() {
  const run = gitArgs => {
    const proc = spawnSync('git', gitArgs, { cwd: root, encoding: 'utf8', windowsHide: true });
    return proc.status === 0 ? proc.stdout.trim() : null;
  };
  const status = run(['status', '--porcelain']);
  return {
    branch: run(['rev-parse', '--abbrev-ref', 'HEAD']),
    commit: run(['rev-parse', 'HEAD']),
    dirty: status === null ? null : status.length > 0,
  };
}

const compilerVersion = spawnSync(csc, ['-version'], { encoding: 'utf8', windowsHide: true });
const buildInfo = {
  schemaVersion: 1,
  version: version,
  builtAtUtc: new Date().toISOString(),
  output: {
    path: path.relative(root, dll).split(path.sep).join('/'),
    bytes: fs.statSync(dll).size,
    sha256: sha256File(dll),
  },
  sdk: {
    dir: sdkDir,
    source: sdk.source,
    version: sdk.version,
    assemblies: adSdk.REQUIRED_DLLS.map(name => ({
      name,
      bytes: fs.statSync(path.join(sdkDir, name)).size,
      sha256: sha256File(path.join(sdkDir, name)),
    })),
  },
  compiler: {
    path: path.relative(root, csc).split(path.sep).join('/'),
    version: (compilerVersion.stdout || '').trim(),
    sha256: sha256File(csc),
  },
  references: {
    list: path.relative(root, refs.file).split(path.sep).join('/'),
    directories: path.relative(root, net48RefDir).split(path.sep).join('/'),
    count: refs.count,
  },
  sources: sources.map(file => ({
    path: relativeToRoot(file),
    bytes: fs.statSync(file).size,
    sha256: sha256File(file),
  })),
  buildArgs: args,
  git: gitSnapshot(),
};
const buildInfoPath = path.join(outDir, 'build-info.json');
fs.writeFileSync(buildInfoPath, JSON.stringify(buildInfo, null, 2) + '\n', 'utf8');

console.log('Built ' + dll);
console.log('sha256: ' + buildInfo.output.sha256);
console.log('rendered: ' + path.relative(root, insOutput) + '  (version ' + version + ')');
console.log('build-info: ' + path.relative(root, buildInfoPath));
